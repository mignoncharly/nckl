export const dictionaries: Record<Locale, Record<string, string>> = { fr, de };

export function normalizeLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith("de") ? "de" : DEFAULT_LOCALE;
}

export function interpolate(message: string, values?: TranslationValues): string {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export function translate(locale: Locale, key: string, values?: TranslationValues): string {
  const message = dictionaries[locale][key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
  return interpolate(message, values);
}

export function localeTag(locale: Locale): string {
  return locale === "de" ? "de-DE" : "fr-FR";
}
